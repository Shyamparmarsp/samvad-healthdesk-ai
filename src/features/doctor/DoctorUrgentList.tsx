import React from 'react';
import { ReportRow } from '../../types/report';

interface DoctorUrgentListProps {
  urgentReports: ReportRow[];
  onSelectReport: (reportId: string) => void;
}

function getInitials(name?: string): string {
  if (!name) return 'PT';
  const parts = name.trim().split(/\s+/);
  if (parts.length >= 2) {
    return (parts[0][0] + parts[parts.length - 1][0]).toUpperCase();
  }
  return parts[0].slice(0, 2).toUpperCase();
}

export const DoctorUrgentList: React.FC<DoctorUrgentListProps> = ({
  urgentReports,
  onSelectReport,
}) => {
  return (
    <div className="space-y-6">
      {/* Top Header matching Figma D7 */}
      <div>
        <h1 className="text-[26px] font-bold text-[#1d2433] tracking-tight">
          Urgent / Review
        </h1>
        <p className="text-[12px] text-[#4a5470] mt-0.5">
          Emergency Triage Queue · Deterministic safety rules and high-priority intake cases
        </p>
      </div>

      {/* Safety Alert Banner */}
      <div className="p-4 rounded-[18px] bg-[rgba(253,226,226,0.85)] border border-white shadow-sm flex items-start gap-3">
        <span className="w-2.5 h-2.5 rounded-full bg-red-600 animate-ping mt-1 shrink-0"></span>
        <div>
          <h2 className="text-[13px] font-bold text-red-950">
            Emergency Triage Queue
          </h2>
          <p className="text-[11px] text-red-900 mt-0.5 leading-relaxed">
            Deterministic emergency triggers generated by the demo intake matcher. Routine appointments are permanently suppressed for all items in this queue.
          </p>
        </div>
      </div>

      {/* Urgent Cards List matching Figma 82:491 */}
      <div className="rounded-[24px] bg-[rgba(255,255,255,0.55)] backdrop-blur-[9px] border border-white p-6 shadow-[0px_7px_22px_-3px_rgba(41,51,79,0.13)] space-y-4">
        {urgentReports.length === 0 ? (
          <div className="p-12 text-center text-xs text-[#4a5470]">
            No urgent triage cases pending at this time.
          </div>
        ) : (
          <div className="divide-y divide-[#dde3ee]/60">
            {urgentReports.map((r) => {
              const isReviewed = Boolean(r.reviewed_at);
              const patientName = r.report.patient.name.value || 'Anonymous Patient';
              const patientAge = r.report.patient.age.value ? `${r.report.patient.age.value} yrs` : 'Age unstated';
              const patientGender = r.report.patient.gender.value || '';
              const concernText = r.report.emergency?.patient_statement || r.report.primary_concern.value;

              return (
                <div
                  key={r.id}
                  onClick={() => onSelectReport(r.id)}
                  onKeyDown={(e) => {
                    if (e.key === 'Enter' || e.key === ' ') {
                      e.preventDefault();
                      onSelectReport(r.id);
                    }
                  }}
                  tabIndex={0}
                  role="button"
                  aria-label={`Open urgent triage report for ${patientName}`}
                  className="py-4 first:pt-0 last:pb-0 flex flex-col sm:flex-row sm:items-center sm:justify-between gap-4 cursor-pointer hover:bg-white/40 -mx-3 px-3 rounded-[16px] transition-colors focus:outline-none focus:ring-2 focus:ring-[#1f2a44]"
                >
                  <div className="flex items-center gap-4">
                    {/* Avatar */}
                    <div className="size-[50px] rounded-full bg-[#e4e8f2] border border-white text-[#1f2a44] font-semibold text-[12px] flex items-center justify-center shrink-0">
                      {getInitials(patientName)}
                    </div>

                    <div>
                      <div className="flex items-center gap-2 mb-1">
                        <span className="text-[10px] font-mono font-semibold text-[#4a5470]">
                          {r.intake_reference}
                        </span>
                        {isReviewed ? (
                          <span className="text-[10px] font-semibold text-[#176a3b] bg-[#dcf3e6] px-2.5 py-0.5 rounded-full">
                            Acknowledged
                          </span>
                        ) : (
                          <span className="text-[10px] font-semibold text-[#a12626] bg-[#fde2e2] px-2.5 py-0.5 rounded-full">
                            Emergency rule
                          </span>
                        )}
                      </div>

                      <h3 className="text-[13px] font-bold text-[#1d2433]">
                        {patientName} · {patientAge} {patientGender ? `· ${patientGender}` : ''}
                      </h3>

                      <p className="text-[11px] text-[#4a5470] mt-0.5 italic">
                        "{concernText}"
                      </p>
                    </div>
                  </div>

                  {/* Flag chip & Open button */}
                  <div className="flex items-center gap-3 shrink-0">
                    <div className="h-[28px] px-3.5 rounded-full bg-[#fde2e2] text-[#a12626] text-[10px] font-semibold flex items-center justify-center">
                      {r.emergency_rule_id || 'severe_chest_pain'}
                    </div>

                    <button
                      type="button"
                      onClick={(e) => {
                        e.stopPropagation();
                        onSelectReport(r.id);
                      }}
                      className="h-[48px] px-6 rounded-[21px] bg-[#1f2a44] text-white font-semibold text-[13px] shadow-[0px_4px_12px_-3px_rgba(41,51,79,0.18)] hover:bg-[#2b3a5d] transition-all flex items-center justify-center"
                    >
                      Open
                    </button>
                  </div>
                </div>
              );
            })}
          </div>
        )}
      </div>
    </div>
  );
};
