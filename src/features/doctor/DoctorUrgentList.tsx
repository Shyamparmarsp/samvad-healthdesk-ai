import React from 'react';
import { ReportRow } from '../../types/report';

interface DoctorUrgentListProps {
  urgentReports: ReportRow[];
  onSelectReport: (reportId: string) => void;
}

export const DoctorUrgentList: React.FC<DoctorUrgentListProps> = ({
  urgentReports,
  onSelectReport,
}) => {
  return (
    <div className="space-y-6">
      {/* Header with High-Visibility Warning Banner */}
      <div className="p-5 rounded-card bg-red-50 border border-red-200 shadow-sm flex items-start gap-3">
        <span className="w-3 h-3 rounded-full bg-red-600 animate-ping mt-1 flex-shrink-0"></span>
        <div>
          <h1 className="text-xl font-bold text-red-950 tracking-tight">
            Emergency Triage Queue
          </h1>
          <p className="text-xs text-red-900 mt-1 leading-relaxed">
            Deterministic emergency triggers generated by the demo intake matcher. Routine appointments are permanently suppressed for all items in this queue.
          </p>
        </div>
      </div>

      {/* Urgent Reports List */}
      <div className="space-y-3">
        {urgentReports.length === 0 ? (
          <div className="p-12 rounded-card bg-white border border-slate-200 text-center text-xs text-slate-400">
            No urgent triage cases pending at this time.
          </div>
        ) : (
          urgentReports.map((r) => {
            const isReviewed = Boolean(r.reviewed_at);
            return (
              <div
                key={r.id}
                onClick={() => onSelectReport(r.id)}
                onKeyDown={(e) => {
                  if (e.key === 'Enter' || e.key === ' ') {
                    e.preventDefault();
                    onSelectReport(r.id);
                  }
                }}
                tabIndex={0}
                role="button"
                aria-label={`Open urgent triage report for ${r.report.patient.name.value || 'Anonymous Patient'}`}
                className="p-5 rounded-card bg-white border border-red-100 hover:border-red-300 shadow-sm transition-all cursor-pointer flex flex-col sm:flex-row sm:items-center sm:justify-between gap-4 focus:outline-none focus:ring-2 focus:ring-red-500"
              >
                <div>
                  <div className="flex items-center gap-2 mb-1">
                    <span className="px-2 py-0.5 rounded text-[10px] font-bold bg-red-100 text-red-800 uppercase tracking-wide">
                      Rule: {r.emergency_rule_id || 'Urgent'}
                    </span>
                    <span className="text-xs font-mono text-slate-400">
                      {r.intake_reference}
                    </span>
                  </div>

                  <h3 className="text-base font-bold text-text-primary">
                    {r.report.patient.name.value || 'Anonymous Patient'}{' '}
                    <span className="text-xs font-normal text-slate-400">
                      ({r.report.patient.age.value ? `${r.report.patient.age.value} yrs` : 'Age unstated'})
                    </span>
                  </h3>

                  <p className="text-xs text-red-900 font-medium mt-1 italic">
                    "{r.report.emergency?.patient_statement || r.report.primary_concern.value}"
                  </p>
                </div>

                <div className="flex items-center gap-4">
                  {isReviewed ? (
                    <span className="text-xs text-emerald-700 font-semibold flex items-center gap-1">
                      <svg className="w-4 h-4" fill="currentColor" viewBox="0 0 20 20">
                        <path fillRule="evenodd" d="M16.707 5.293a1 1 0 010 1.414l-8 8a1 1 0 01-1.414 0l-4-4a1 1 0 011.414-1.414L8 12.586l7.293-7.293a1 1 0 011.414 0z" clipRule="evenodd" />
                      </svg>
                      Acknowledged
                    </span>
                  ) : (
                    <span className="px-2.5 py-1 rounded-full bg-red-100 text-red-800 text-[11px] font-bold uppercase tracking-wider">
                      Pending Action
                    </span>
                  )}

                  <span className="text-xs font-bold text-brand-navy hover:underline">
                    View &rarr;
                  </span>
                </div>
              </div>
            );
          })
        )}
      </div>
    </div>
  );
};

